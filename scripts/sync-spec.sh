#!/usr/bin/env bash
# Vendors the Uptrace API spec into openapi/openapi.yaml as one bundled file.
#
# The spec lives in the app repository as a tree of files (openapi/). This script
# takes that tree at a git ref, drops the x-vocabularies list (documentation
# that refers to components no operation uses, which the generator cannot
# resolve), and bundles it with the Redocly CLI the app itself pins.
#
# Bundle from the oldest app version the provider must support: the server
# rejects a request key its spec does not list, so a newer spec can make the
# provider send a key an older server refuses.
#
# Usage: scripts/sync-spec.sh <app-checkout> <git-ref>
set -euo pipefail

app_dir=${1:?usage: scripts/sync-spec.sh <app-checkout> <git-ref>}
ref=${2:?usage: scripts/sync-spec.sh <app-checkout> <git-ref>}
redocly_version=2.14.6

root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

commit=$(git -C "$app_dir" rev-parse --verify "$ref^{commit}")
git -C "$app_dir" archive "$commit" openapi | tar -x -C "$work"

# Remove the top-level x-vocabularies block: from its key to the next
# top-level key.
awk '
  /^x-vocabularies:/ { skip = 1; next }
  skip && /^[^ #-]/ { skip = 0 }
  !skip
' "$work/openapi/openapi.yaml" >"$work/openapi/openapi.stripped.yaml"
mv "$work/openapi/openapi.stripped.yaml" "$work/openapi/openapi.yaml"

(cd "$work/openapi" && npx -y "@redocly/cli@$redocly_version" bundle openapi.yaml -o "$work/bundled.yaml" >/dev/null)

{
  echo "# Generated by scripts/sync-spec.sh from the uptrace app repository,"
  echo "# openapi/ at commit $commit ($ref). Do not edit."
  cat "$work/bundled.yaml"
} >"$root/openapi/openapi.yaml"

echo "openapi/openapi.yaml: app $ref ($commit)"
